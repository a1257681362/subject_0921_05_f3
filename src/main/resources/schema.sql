-- H2 本地文件数据库初始化脚本。连锁眼镜店：验光与加工底账。
-- 约定：全库禁止物理删除；作废/冲销均以状态位体现并写操作日志；
-- 每张业务表带操作人、请求号、业务时间、版本号；重复提交由唯一约束兜底。

-- ---------------------------------------------------------------------------
-- 骨架版本表
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- ---------------------------------------------------------------------------
-- 镜片基础信息
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_lens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lens_code       VARCHAR(64)  NOT NULL,
    lens_name       VARCHAR(128) NOT NULL,
    brand           VARCHAR(64),
    lens_type       VARCHAR(32),
    refractive_index VARCHAR(16),
    price           DECIMAL(10, 2),
    lens_status     VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE / DISCARDED
    remark          VARCHAR(255),
    created_by      BIGINT,
    created_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by      BIGINT,
    updated_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no      VARCHAR(64),
    biz_time        TIMESTAMP,
    version_no      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_lens_code UNIQUE (lens_code)
);

CREATE TABLE IF NOT EXISTS t_lens_oper_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lens_id      BIGINT       NOT NULL,
    oper_type    VARCHAR(16)  NOT NULL,   -- CREATE / UPDATE / DISCARD / RESTORE
    oper_remark  VARCHAR(255),
    oper_by      BIGINT,
    request_no   VARCHAR(64),
    biz_time     TIMESTAMP,
    version_no   BIGINT
);

-- ---------------------------------------------------------------------------
-- 加工单主表
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_process_order (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no       VARCHAR(64)  NOT NULL,
    customer_name  VARCHAR(64),
    customer_phone VARCHAR(32),
    store_code     VARCHAR(32),
    lens_id        BIGINT       NOT NULL,
    order_status   VARCHAR(16)  NOT NULL DEFAULT 'CREATED',
                    -- CREATED 已建档 / PROCESSING 加工中 / READY 待取镜 / PICKED_UP 已取镜 / CANCELLED 已冲销
    remark         VARCHAR(255),
    created_by     BIGINT,
    created_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by     BIGINT,
    updated_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no     VARCHAR(64),
    biz_time       TIMESTAMP,
    version_no     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_order_no       UNIQUE (order_no),
    CONSTRAINT uk_order_request  UNIQUE (request_no)   -- 库层兜底重复提交
);

-- ---------------------------------------------------------------------------
-- 加工单处方明细（左右眼各一行）
-- 编辑加工单时不物理删除旧行：旧行置 VOID，新行重新插入，与主表同一事务。
-- active_eye 为生成列：仅 ACTIVE 行参与唯一约束，保证每只眼最多一条有效处方。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_process_order_rx (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT      NOT NULL,
    eye           VARCHAR(8)  NOT NULL,                  -- L / R
    sphere        DECIMAL(5, 2),                         -- 球镜 S
    cylinder      DECIMAL(5, 2),                         -- 柱镜 C（散光）
    axis          INT,                                   -- 轴位 1~180
    add_power     DECIMAL(4, 2),                         -- 下加光 ADD
    pd            INT,                                   -- 瞳距 mm
    record_status VARCHAR(8)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / VOID
    active_eye    VARCHAR(8) GENERATED ALWAYS AS (CASE WHEN record_status = 'ACTIVE' THEN eye ELSE NULL END),
    created_by    BIGINT,
    created_time  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by    BIGINT,
    updated_time  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no    VARCHAR(64),
    biz_time      TIMESTAMP,
    version_no    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_order_rx_active UNIQUE (order_id, active_eye)
);

-- ---------------------------------------------------------------------------
-- 加工单取镜状态流转日志（只追加）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_process_order_status_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT      NOT NULL,
    oper_type   VARCHAR(16) NOT NULL,  -- CREATE / START / FINISH / PICKUP / CANCEL / RESTORE
    from_status VARCHAR(16),
    to_status   VARCHAR(16) NOT NULL,
    oper_remark VARCHAR(255),
    oper_by     BIGINT,
    request_no  VARCHAR(64),
    biz_time    TIMESTAMP,
    version_no  BIGINT
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ---------------------------------------------------------------------------
-- 加工单文本敏感词扫描留痕（只追加）
-- 每次扫描（含无命中的 PASS）按加工单按字段留一行：命中明细、处置动作、词库版本，
-- 供别组取数与"以加工单为准"的反向核对（RECHECK 行由核对接口写入）。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_sensitive_scan_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT,                   -- 被拦截（BLOCK）时加工单未建档，可空
    order_no     VARCHAR(64),
    field_name   VARCHAR(32)  NOT NULL,    -- customerName / remark
    action       VARCHAR(16)  NOT NULL,    -- PASS / MASK / BLOCK / RECHECK
    hit_count    INT          NOT NULL DEFAULT 0,
    hit_detail   VARCHAR(4000),            -- JSON：[{"word","level","start","end"}]，原文坐标；超长截断（hit_count 仍准确）
    dict_version VARCHAR(64)  NOT NULL,    -- 词库版本（内容 MD5 短串）
    oper_type    VARCHAR(16)  NOT NULL,    -- CREATE / UPDATE / RECHECK
    created_by   BIGINT,
    created_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by   BIGINT,
    updated_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no   VARCHAR(64),
    biz_time     TIMESTAMP,
    version_no   BIGINT       NOT NULL DEFAULT 0
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('lens-order-1', '镜片基础信息与加工单（验光/取镜流转/检索）底账');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('sensitive-1', '加工单文本敏感词扫描留痕与反向核对');

-- ---------------------------------------------------------------------------
-- 后台批量任务（任务号查进度、可取消、失败断点重跑、记录保留 21 天）
-- 任务状态机：PENDING 待执行 → RUNNING 执行中 → SUCCESS 全部成功 / FAILED 有失败项（可重跑）
--             PENDING/RUNNING/FAILED → CANCEL_REQUESTED 收到取消请求 → CANCELLED 已取消（已处理项保留）
-- 全库禁止物理删除：清理以 expire_status 状态位 + 状态时间体现，行保留可查（默认 21 天转 ARCHIVED）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_batch_task (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no         VARCHAR(64)  NOT NULL,               -- 任务号（查询进度用），如 BT-20260927-000001
    task_type       VARCHAR(32)  NOT NULL,               -- 任务类型，如 SENSITIVE_RECHECK
    params          VARCHAR(2000),                       -- JSON 任务参数（如 {"storeCode":"S01"}）
    status          VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
                    -- PENDING / RUNNING / SUCCESS / FAILED / CANCEL_REQUESTED / CANCELLED / ARCHIVED
    total_count     INT          NOT NULL DEFAULT 0,     -- 待处理总条数
    processed_count INT          NOT NULL DEFAULT 0,     -- 已处理（成功+失败，不含待处理）
    success_count   INT          NOT NULL DEFAULT 0,
    fail_count      INT          NOT NULL DEFAULT 0,
    progress_pct    INT          NOT NULL DEFAULT 0,     -- 量化到 5% 一档：0,5,10,...,100
    last_order_id   BIGINT,                              -- 游标：最后处理到的加工单 id（断点参考）
    error_message   VARCHAR(2000),                       -- 任务级错误（整体启动失败等）
    result_json     VARCHAR(4000),                       -- 任务级结果汇总（recheck：词库版本/总数/一致字段数；明细在 item）
    created_by      BIGINT,
    created_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by      BIGINT,
    updated_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_time    TIMESTAMP,
    finished_time   TIMESTAMP,
    cancel_requested_time TIMESTAMP,
    status_set_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- 进入当前状态的时间（清理/恢复判定用）
    expire_days     INT          NOT NULL DEFAULT 21,    -- 记录保留天数
    expire_status   VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',  -- ACTIVE / ARCHIVED（21 天转归档，不物理删除）
    request_no      VARCHAR(64),
    biz_time        TIMESTAMP,
    version_no      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_batch_task_no UNIQUE (task_no)
);

-- ---------------------------------------------------------------------------
-- 批量任务处理项（断点续跑依据：每加工单一项，记录处理结果）
-- 重跑时只捞 PENDING/FAILED 的项继续；SUCCESS 的跳过。同一任务内 item_ref 唯一。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_batch_task_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       BIGINT       NOT NULL,
    item_ref      VARCHAR(64)  NOT NULL,   -- 处理对象标识（recheck 为加工单号 order_no）
    target_id     BIGINT,                  -- 加工单 id（排序/定位用）
    item_status   VARCHAR(16)  NOT NULL DEFAULT 'PENDING',  -- PENDING / SUCCESS / FAILED / SKIPPED
    error_message VARCHAR(1000),
    result_json   VARCHAR(2000),           -- 单项结果摘要（recheck：各字段处置/drift 标记）
    attempt       INT          NOT NULL DEFAULT 0,  -- 已尝试次数
    created_by    BIGINT,
    created_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by    BIGINT,
    updated_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no    VARCHAR(64),
    biz_time      TIMESTAMP,
    version_no    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_batch_task_item UNIQUE (task_id, item_ref)
);

CREATE INDEX IF NOT EXISTS idx_batch_task_item_status ON t_batch_task_item (task_id, item_status);

-- 任务号序列（BT-日期-6 位序号），H2 持久化序列、重启不回退（默认 BIGINT）
CREATE SEQUENCE IF NOT EXISTS seq_batch_task_no START WITH 1;

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('batch-task-1', '后台批量任务：任务号查进度（5%档）、可取消、失败断点重跑、记录归档（21天）');
